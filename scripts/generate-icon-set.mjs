// Extracts the icons the Davipress theme renders itself into src/runtime/icon-set.tsx,
// so the published bundle never pulls a multi-megabyte davi-icons pack.
// Run with: npm run icons

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const packsDir = path.join(root, 'node_modules/davi-icons/dist/icons')

const names = [
  'FaBook', 'FaCertificate', 'FaCode', 'FaDockerBrands', 'FaGear', 'FaGraduationCap', 'FaHouse',
  'FaJavaBrands', 'FaLayerGroup', 'FaMoon', 'FaPenNib', 'FaRocket', 'FaRss', 'FaStarRegular',
  'FaSun', 'FaUser', 'FaUserPen',
  'GiEvilBook', 'GiFrogPrince', 'GiMagicPortal', 'GiSpellBook',
  'DvAnkhWingsTome', 'DvTerminalBlink',
  'MdCalendarRange', 'MdFormatListBulleted', 'MdHistory', 'MdPencilOutline',
  'IoClose', 'IoTimerOutline',
  'FiGithub', 'FiYoutube',
  'TbBrandAdobe', 'TbBrandFacebook', 'TbBrandHackerrank', 'TbBrandLinkedin', 'TbBrandMysql',
  'TbBrandTiktok', 'TbMenu2FilledFilled',
  'DiMicrosoftsqlserverPlain',
  'SiCmake', 'SiCplusplus', 'SiCss', 'SiDart', 'SiGo', 'SiHtml5', 'SiJavascript', 'SiKotlin',
  'SiLeetcode', 'SiNextdotjs', 'SiPhp', 'SiPython', 'SiReact', 'SiRust', 'SiSass', 'SiSharp',
  'SiSwift', 'SiTailwindcss', 'SiTypescript', 'SiVuedotjs'
]

const sources = new Map()
function packSource(pack) {
  if (!sources.has(pack)) sources.set(pack, fs.readFileSync(path.join(packsDir, `${pack}.js`), 'utf8'))
  return sources.get(pack)
}

function extract(name) {
  const source = packSource(name.slice(0, 2).toLowerCase())
  const marker = `export const ${name} = createDaviIcon(`
  const start = source.indexOf(marker)
  if (start === -1) throw new Error(`Icon not found in davi-icons: ${name}`)
  let index = source.indexOf('{', start)
  let depth = 0
  for (let cursor = index; cursor < source.length; cursor++) {
    if (source[cursor] === '{') depth++
    else if (source[cursor] === '}' && --depth === 0) {
      const icon = JSON.parse(source.slice(index, cursor + 1))
      return { viewBox: icon.viewBox, nodes: icon.nodes }
    }
  }
  throw new Error(`Unterminated icon definition: ${name}`)
}

const body = names
  .map(name => `export const ${name} = createIcon(${JSON.stringify(extract(name))})`)
  .join('\n')

fs.writeFileSync(
  path.join(root, 'src/runtime/icon-set.tsx'),
  `// AUTO-GENERATED by scripts/generate-icon-set.mjs. Do not edit manually.\nimport { createIcon } from './icon-base.js'\n\n${body}\n`
)

console.log(`Generated ${names.length} icons into src/runtime/icon-set.tsx`)
